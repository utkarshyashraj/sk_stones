// Runs after `next build` (static export). Writes Netlify `_redirects` (301s for legacy URLs) and `_headers`.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'out');
if (!fs.existsSync(OUT)) {
  console.error('out/ not found — run next build first');
  process.exit(1);
}

// Windows-only Next.js export bug: segment prefetch files are written as `<route>/__next.<seg>/<rest>.txt`
// (backslash path joined) instead of the flat `<route>/__next.<seg>.<rest>.txt` the client router requests.
// Flatten them so local Windows builds match Linux (Netlify) builds. No-op when nothing needs fixing.
let flattened = 0;
const flatten = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (!e.isDirectory()) continue;
    if (e.name.startsWith('__next.')) {
      const files = [];
      const collect = (d, rel) => {
        for (const f of fs.readdirSync(d, { withFileTypes: true })) {
          const fp = path.join(d, f.name);
          if (f.isDirectory()) collect(fp, [...rel, f.name]);
          else files.push({ fp, rel: [...rel, f.name] });
        }
      };
      collect(p, []);
      for (const f of files) {
        fs.renameSync(f.fp, path.join(dir, `${e.name}.${f.rel.join('.')}`));
        flattened++;
      }
      fs.rmSync(p, { recursive: true, force: true });
    } else if (e.name !== '_next' && e.name !== 'images' && e.name !== 'media') flatten(p);
  }
};
flatten(OUT);
if (flattened)
  console.log(`postbuild: flattened ${flattened} segment prefetch files (Windows export path fix).`);

const { pages } = JSON.parse(fs.readFileSync(path.join(ROOT, 'content/legacy-urls.json'), 'utf8'));
const { retiredLegacyPages } = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'content/generated/catalog.json'), 'utf8'),
);
const retired = new Map(retiredLegacyPages.map((r) => [r.slug, `/${r.redirectTo}`]));

// Must mirror lib/routes.ts legacyRedirects() (unit-tested there).
const rules = [];
for (const [slug, to] of retired) rules.push([`/${slug}`, to]);
for (const page of pages) {
  const slug = page.replace(/\.html$/, '');
  const to = slug === 'index' ? '/' : (retired.get(slug) ?? `/${slug}`);
  rules.push([`/${slug}.html`, to]);
}
// GitHub Pages build (folder-style URLs): Pages has no server-side redirects, so each legacy URL gets
// a tiny redirect page (meta refresh + location.replace, canonical to the new URL, noindex), and
// .nojekyll stops Pages from hiding the _next/ folder. Netlify files are not written in this mode.
const PAGES = process.env.NEXT_PUBLIC_TRAILING_SLASH === '1';
if (PAGES) {
  const SITE = (process.env.NEXT_PUBLIC_SITE_URL || 'https://skstonesindia.com').replace(/\/+$/, '');
  fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
  let stubs = 0;
  for (const [from, to] of rules) {
    const target = to === '/' ? '/' : `${to}/`;
    const file = from.endsWith('.html') ? path.join(OUT, from) : path.join(OUT, from, 'index.html');
    if (fs.existsSync(file)) continue; // a real page lives here
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(
      file,
      `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Moved</title>` +
        `<meta name="robots" content="noindex"><link rel="canonical" href="${SITE}${target}">` +
        `<meta http-equiv="refresh" content="0; url=${target}">` +
        `<script>location.replace(${JSON.stringify(target)} + location.search + location.hash)</script>` +
        `</head><body><p>This page has moved: <a href="${target}">continue</a>.</p></body></html>
`,
    );
    stubs++;
  }
  console.log(`postbuild (GitHub Pages): ${stubs} legacy redirect pages, .nojekyll written.`);
}

// force (!) so the redirect wins even though a file like /about.html exists in the export.
const redirects = [
  '# Generated by scripts/postbuild.mjs — legacy URLs -> current pretty URLs (permanent).',
  ...rules.map(([from, to]) => `${from}  ${to}  301!`),
  '',
].join('\n');
if (!PAGES) fs.writeFileSync(path.join(OUT, '_redirects'), redirects);

const headers = `# Generated by scripts/postbuild.mjs
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: SAMEORIGIN
  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()
  Strict-Transport-Security: max-age=31536000; includeSubDomains

/_next/static/*
  Cache-Control: public, max-age=31536000, immutable

/images/*
  Cache-Control: public, max-age=2592000, stale-while-revalidate=86400

/media/*
  Cache-Control: public, max-age=2592000

/data/*
  Cache-Control: public, max-age=3600, stale-while-revalidate=86400
`;
if (!PAGES) fs.writeFileSync(path.join(OUT, '_headers'), headers);

// Sanity: no file in the export may reference the old staging host.
const offenders = [];
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (
      /\.(html|txt|json|js|css|xml)$/.test(e.name) &&
      fs.readFileSync(p, 'utf8').includes('hostingersite.com')
    )
      offenders.push(path.relative(OUT, p));
  }
};
walk(OUT);
if (offenders.length) {
  console.error(`ERROR: staging host referenced in ${offenders.length} file(s):\n${offenders.join('\n')}`);
  process.exit(1);
}
console.log(
  PAGES
    ? 'postbuild: no staging-host references.'
    : `postbuild: ${rules.length} redirects, _headers written, no staging-host references.`,
);
