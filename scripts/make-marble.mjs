// Builds the site-wide marble layer from the company's own Nero Portoro slab photograph and VERIFIES text
// contrast against the busiest part of the stone with every veil level applied.
//
//   node scripts/make-marble.mjs            -> writes public/images/marble/*, content/generated/marble.json
//
// Contrast method: take the 99.9th-percentile brightest pixels of the processed slab (the veins), composite
// the veil (#100E0C at alpha) over them exactly as the browser does (sRGB "normal" blending), and compute the
// WCAG ratio for each text colour. The build fails if body text drops below 4.5:1.
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, '.cache/legacy-src/nero-portoro-compressed-scaled-79a4a8.webp');
const OUT = path.join(ROOT, 'public/images/marble');
const BRIGHTNESS = 0.55; // slab tone — chosen so every check below passes with margin
const VEIL = [16, 14, 12]; // #100E0C
const VEILS = { hero: 0.45, mid: 0.75, text: 0.9 };
const PANEL = { color: [20, 17, 15], alpha: 0.72 }; // text panels sit on top of the veil
const TEXT = {
  text: '#f5f1e9',
  text2: '#b8b1a6',
  text3: '#9a9287',
  accent: '#b08d57',
  accentHero: '#d9bc8c',
};
// Which text colours must pass AA (4.5:1) at each veil level. Hero/CTA zones use --text for copy and the
// lighter champagne --accent-hero for gold type (see .zone-hero in globals.css).
const REQUIRED = {
  hero: ['text', 'accentHero'],
  mid: ['text', 'text2', 'accent'],
  text: ['text', 'text2', 'text3', 'accent'],
};

fs.mkdirSync(OUT, { recursive: true });
const base = sharp(SRC)
  .extract({ left: 0, top: 160, width: 2560, height: 1283 }) // drop the glare-prone top edge
  .modulate({ brightness: BRIGHTNESS, saturation: 0.85 });

const outputs = [];
for (const width of [1200, 2400]) {
  const r = base.clone().resize({ width });
  const avif = path.join(OUT, `nero-portoro-${width}.avif`);
  const webp = path.join(OUT, `nero-portoro-${width}.webp`);
  await r.clone().avif({ quality: 48, effort: 6 }).toFile(avif);
  await r.clone().webp({ quality: 66, effort: 6 }).toFile(webp);
  outputs.push([avif, webp]);
}
const blur = await base.clone().resize({ width: 24 }).webp({ quality: 40 }).toBuffer();
const meta = await sharp(path.join(OUT, 'nero-portoro-2400.webp')).metadata();

// ---------- contrast verification ----------
const { data } = await base.clone().resize({ width: 1200 }).raw().toBuffer({ resolveWithObject: true });
const lin = (c) => {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const L = ([r, g, b]) => 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
const hex = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const ratio = (a, b) => {
  const [x, y] = [L(a), L(b)].sort((m, n) => n - m);
  return (x + 0.05) / (y + 0.05);
};
const lum = [];
for (let i = 0; i < data.length; i += 3) lum.push([L([data[i], data[i + 1], data[i + 2]]), i]);
lum.sort((a, b) => a[0] - b[0]);
const idx = lum[Math.floor(lum.length * 0.999)][1];
const busiest = [data[idx], data[idx + 1], data[idx + 2]];
const over = (top, alpha, under) => top.map((c, i) => Math.round(c * alpha + under[i] * (1 - alpha)));

let ok = true;
const report = {};
for (const [name, alpha] of Object.entries(VEILS)) {
  const bg = over(VEIL, alpha, busiest);
  report[name] = {};
  for (const [t, h] of Object.entries(TEXT)) {
    const r = ratio(hex(h), bg);
    report[name][t] = Math.round(r * 100) / 100;
    if (REQUIRED[name].includes(t) && r < 4.5) ok = false;
  }
}
const panelBg = over(PANEL.color, PANEL.alpha, over(VEIL, VEILS.mid, busiest));
report.panel = Object.fromEntries(
  Object.entries(TEXT).map(([t, h]) => [t, Math.round(ratio(hex(h), panelBg) * 100) / 100]),
);

fs.writeFileSync(
  path.join(ROOT, 'content/generated/marble.json'),
  JSON.stringify(
    {
      $comment: 'GENERATED by scripts/make-marble.mjs',
      src: '/images/marble/nero-portoro-2400.webp',
      srcAvif: '/images/marble/nero-portoro-2400.avif',
      srcSmall: '/images/marble/nero-portoro-1200.webp',
      width: meta.width,
      height: meta.height,
      blurDataURL: `data:image/webp;base64,${blur.toString('base64')}`,
      busiestPixel: `rgb(${busiest.join(',')})`,
      contrast: report,
    },
    null,
    1,
  ),
);
for (const pair of outputs)
  for (const f of pair) console.log(path.basename(f), Math.round(fs.statSync(f).size / 1024), 'KB');
console.log('busiest marble pixel (99.9th pct):', busiest, '\ncontrast (WCAG) with veil applied:', report);
if (!ok) {
  console.error('FAIL: body text below 4.5:1 on the busiest marble — lower BRIGHTNESS or raise the veil.');
  process.exit(1);
}
console.log('OK: all required text colours pass AA on the busiest marble.');
