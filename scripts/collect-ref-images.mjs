// Registers every image the reference's non-catalogue pages use (home, about, projects, contact, services,
// thank-you), so the ported markup can keep the reference's own image paths: content/ref-images.json maps
// each original src (as written in the reference HTML) to a site image key, and content/site-images.json
// gets a matching `ref-…` entry (local legacy/ file or staging-host URL) for build-catalog/optimize-images.
// Usage: node scripts/collect-ref-images.mjs   (then catalog:download, catalog:build, images:optimize)
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const LEGACY = path.join(ROOT, 'legacy');
const PAGES = [
  'index',
  'about',
  'projects',
  'contact',
  'thank-you',
  'landscaping',
  'flooring-executions',
  'stone-art-installations',
  'installations',
];

const srcs = new Set();
for (const page of PAGES) {
  const html = fs.readFileSync(path.join(LEGACY, `${page}.html`), 'utf8').replace(/<!--[\s\S]*?-->/g, ''); // commented-out sections (e.g. the retired hero) are not part of the page
  for (const m of html.matchAll(/<img\b[^>]*?\s(?:src|data-src)=["']([^"']+)["']/g)) srcs.add(m[1]);
  for (const m of html.matchAll(/background(?:-image)?:\s*url\(["']?([^"')]+\.(?:jpe?g|png|webp))["']?\)/g))
    srcs.add(m[1]);
}

const key = (src) =>
  'ref-' +
  decodeURIComponent(
    src
      .split('/')
      .pop()
      .replace(/[?#].*$/, ''),
  )
    .replace(/\.[a-z0-9]+$/i, '')
    .toLowerCase()
    .replace(/-e\d{9,}$/, '') // WordPress "edited" suffix
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60);

const map = {};
const used = new Map(); // key -> source
const siteImages = JSON.parse(fs.readFileSync(path.join(ROOT, 'content/site-images.json'), 'utf8'));
for (const src of [...srcs].sort()) {
  if (src.startsWith('data:')) continue;
  const source = /^https?:/.test(src)
    ? src
    : `legacy/${decodeURIComponent(src.replace(/^\//, '').replace(/[?#].*$/, ''))}`;
  if (!/^https?:/.test(source) && !fs.existsSync(path.join(ROOT, source))) {
    console.log('missing on disk (skipped):', source);
    continue;
  }
  let k = key(src);
  for (let n = 2; used.has(k) && used.get(k) !== source; n++) k = `${key(src)}-${n}`;
  used.set(k, source);
  map[src] = `site/${k}`;
  siteImages.images[k] = source;
}
fs.writeFileSync(
  path.join(ROOT, 'content/ref-images.json'),
  JSON.stringify(
    {
      $comment: 'GENERATED by scripts/collect-ref-images.mjs — reference image src -> site image key.',
      images: map,
    },
    null,
    2,
  ) + '\n',
);
fs.writeFileSync(path.join(ROOT, 'content/site-images.json'), JSON.stringify(siteImages, null, 2) + '\n');
console.log(`reference images registered: ${Object.keys(map).length} (${used.size} unique files)`);
